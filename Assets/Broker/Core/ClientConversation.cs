namespace Broker.Core
{
    // Scripted personalities; optional model phrasing never decides game rules.
    public static class ClientConversation
    {
        public static string Needs(string id) => id == "boris"
            ? "Через год покупаю оборудование. Четвёртую мойку пока купил только на бумаге."
            : id == "inna" ? "Разместить часть свободного капитала на понятный срок. Не финансировать вашу уверенность."
            : "Хочу личное сопровождение. В массовой рассылке я уже был особенным, спасибо.";
        public static string Risk(string id) => id == "boris"
            ? "То есть можно потерять деньги. Хорошо, что сказали до того, как я продал пылесосы."
            : id == "inna" ? "Риск убытка зафиксировала. Обещания чудес оставим рекламному отделу."
            : "Понял, риск есть даже у особенных клиентов. Неприятно, но честно.";
        public static string Fee(string id) => id == "boris"
            ? "Два процента вам. Наконец число, которое помещается на салфетке."
            : id == "inna" ? "Комиссия 2%. Теперь это условие, а не сюрприз в приложении к договору."
            : "Комиссия 2%. Надеюсь, моё имя в эти деньги тоже входит.";
        public static string Objection(string id) => id == "boris"
            ? "А если деньги понадобятся на оборудование раньше? Вложить всё и ходить вокруг сломанной мойки?"
            : id == "inna" ? "На словах всё гладко. Где комиссия и условия будут зафиксированы письменно?"
            : "После перевода денег мне ответит человек или меню из девяти кнопок? Кто останется на связи?";
        public static string Hint(string id) => id == "boris"
            ? "Обсуди резерв: не вкладывать всю сумму, оставить деньги на оборудование."
            : id == "inna" ? "Обсуди письменные условия: договор с зафиксированной комиссией."
            : "Назови личный контакт: менеджер, прямой номер или «буду на связи».";
        public static DialogueIntent AnswerIntent(string id) => id == "boris" ? DialogueIntent.Reserve
            : id == "inna" ? DialogueIntent.Written : DialogueIntent.Contact;
        public static string ObjectionAnswered(string id) => id == "boris"
            ? "Оставить резерв, а не вкладывать всё. Вот теперь похоже на план, а не на залог автомойки."
            : id == "inna" ? "Письменный договор с условиями — это уже разговор. Печать «очень солидно» не обязательна."
            : "Личный контакт после сделки? Отлично. Запишу вас не как «неизвестный брокер №4».";
        public static string Pressure(string id) => id == "boris"
            ? "Если только сегодня, то без меня. Мои мойки тоже работают завтра. Не давите."
            : id == "inna" ? "Срочность вместо аргументов? Зафиксировала снижение доверия."
            : "Последний шанс? Звучит как массовая распродажа. Я просил особое отношение, а не давление.";
        public static string Respect(string id) => id == "boris"
            ? "Без спешки — другое дело. Теперь можно нормально поговорить."
            : id == "inna" ? "Решение действительно за мной. Вернёмся к условиям без давления."
            : "Спасибо, что не торопите. В очереди за уникальностью я уже постоял.";
        public static string Unclear(string id, int attempt)
        {
            if (id == "boris") return attempt % 2 == 0
                ? "Красиво. А теперь так, чтобы я мог пересказать это между двумя мойками."
                : "Вывеску я оценил. Давайте к моим деньгам и конкретным условиям.";
            if (id == "inna") return attempt % 2 == 0
                ? "Это пока рекламный текст. Мне нужны проверяемые условия."
                : "Записала: много уверенности. Цифр и условий пока не прибавилось.";
            return attempt % 2 == 0 ? "Звучит солидно. Это вы всем говорите или специально мне?"
                : "Если убрать слово «эксклюзивно», что останется лично для меня?";
        }
    }
}
